#!/usr/bin/env python
"""Write device/explain_vocab.py: every word the training answers and fact sentences use, so the runtime checker can reject an
answer that steps outside them. Sources are the rule-based composer's strings and its training and validation targets, never
held-out text. The composer's own strings are included because rare cases, such as a nearly uniform frame, may not be in the sample.

usage: build_vocab.py [--data data/llm/finetune] [--out device/explain_vocab.py]
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import textwrap
from pathlib import Path

WORD = re.compile(r"[a-z]+")


def words_of(path: Path) -> set:
    out = set()
    for line in path.read_text().splitlines():
        for m in json.loads(line)["messages"]:
            if m["role"] != "system":
                out |= set(WORD.findall(m["content"].lower()))
    return out


def composer_words(path: Path) -> set:
    out = set()
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            out |= set(WORD.findall(node.value.lower()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/llm/finetune")
    ap.add_argument("--out", default="device/explain_vocab.py")
    a = ap.parse_args()
    composer = Path(__file__).with_name("composer.py")
    vocab = sorted(words_of(Path(a.data) / "train.jsonl") | words_of(Path(a.data) / "val.jsonl") | composer_words(composer))
    body = "\n".join(textwrap.wrap(" ".join(vocab), 120))
    Path(a.out).write_text('"""Generated by scripts/llm/finetune/build_vocab.py: the words of the explainer\'s training answers and fact '
                           'sentences.\nexplain_check rejects an answer using any other word, which stops invented content in '
                           'phrasings no pattern lists."""\n'
                           f'VOCAB = frozenset("""\n{body}\n""".split())\n')
    print(len(vocab), "words")


if __name__ == "__main__":
    main()
